/** 年家奇门：年份所在「三元九运」元次（上元 1864-1923、中元 1924-1983、下元 1984-2043，180 年一轮）。 */
export function yearEpoch(year) {
  const y = Math.trunc(year);
  const cycle = ((y - 1864) % 180 + 180) % 180;
  if (cycle < 60) return '上元';
  if (cycle < 120) return '中元';
  return '下元';
}

